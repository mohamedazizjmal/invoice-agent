"""
Measures the validation layer as a classifier: does "needs_review" agree
with whether the extraction actually had an error, against real ground
truth? Reuses the real-OCR predictions already generated by
colab_end_to_end_eval.ipynb -- no model re-run needed.

A good validation layer should have HIGH RECALL on actual errors (catch
most of what's wrong) even at some cost to precision: flagging a correct
extraction costs a human a few seconds, while missing a real error is the
expensive failure mode this layer exists to prevent.

Two views of "actually wrong" are reported:
- ANY field wrong (strict: includes e.g. one garbled character in an
  Arabic product description).
- CRITICAL field wrong (identity + money fields, see CRITICAL_FIELDS
  below). Which fields count as critical is a judgment call about what a
  business cares about most -- edit the list to match your priorities.

Usage (run from inside the repo, e.g. in Colab):
    python3 analyze_validation_layer.py --gold dataset_full/test.jsonl --predictions results/finetuned_real_ocr_predictions.jsonl
"""

import argparse
import json
from collections import Counter

import eval_harness
import validation

CRITICAL_FIELDS = ["invoice_number", "issue_date", "vendor_tax_id",
                   "subtotal", "vat_rate", "vat_amount", "grand_total"]

SCALAR_FIELDS = eval_harness.SCALAR_FIELDS


def wrong_fields(gold_labels, pred):
    """Names of the fields where the prediction diverges from gold."""
    counts = eval_harness.score_record(gold_labels, pred)
    return [name for name, c in counts.items() if c["fp"] > 0 or c["fn"] > 0]


def describe_miss(rid, gold, pred, bad_fields):
    print(f"\nrecord: {rid}")
    print(f"  fields that differ: {', '.join(bad_fields)}")
    pred_dict = pred if isinstance(pred, dict) else {}
    for f in bad_fields:
        if f in SCALAR_FIELDS:
            print(f"    {f}: gold={gold.get(f)!r}  pred={pred_dict.get(f)!r}")
    if any(f not in SCALAR_FIELDS for f in bad_fields):
        pred_items = pred_dict.get("line_items")
        n_pred = len(pred_items) if isinstance(pred_items, list) else 0
        n_gold = len(gold.get("line_items") or [])
        print(f"    line items: {n_gold} in gold, {n_pred} in prediction")


def ratio(a, b):
    return a / b if b else float("nan")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--gold", required=True)
    p.add_argument("--predictions", required=True,
                    help="JSONL cache from run_eval_resumable: {record_id, raw_pred} per line")
    p.add_argument("--show-examples", type=int, default=10,
                    help="How many missed-error (false negative) examples to print")
    args = p.parse_args()

    gold_by_id = {}
    with open(args.gold, encoding="utf-8") as f:
        for line in f:
            rec = json.loads(line)
            gold_by_id[rec["labels"]["record_id"]] = rec["labels"]

    raw_preds_by_id = {}
    with open(args.predictions, encoding="utf-8") as f:
        for line in f:
            entry = json.loads(line)
            raw_preds_by_id[entry["record_id"]] = entry["raw_pred"]

    seen_keys = set()
    tp = fp = fn = tn = 0
    misses = []
    missed_field_counter = Counter()
    critical_total = critical_caught = 0

    for rid, gold in gold_by_id.items():
        raw = raw_preds_by_id.get(rid)
        if raw is None:
            continue  # no cached prediction for this record yet
        pred = eval_harness.extract_json(raw) if isinstance(raw, str) else None

        result = validation.validate_extraction(pred, seen_keys=seen_keys)
        bad = wrong_fields(gold, pred)
        actually_wrong = len(bad) > 0
        critical_wrong = any(f in CRITICAL_FIELDS for f in bad)

        if critical_wrong:
            critical_total += 1
            if result.needs_review:
                critical_caught += 1

        if result.needs_review and actually_wrong:
            tp += 1
        elif result.needs_review and not actually_wrong:
            fp += 1
        elif not result.needs_review and actually_wrong:
            fn += 1
            misses.append((rid, gold, pred, bad))
            missed_field_counter.update(bad)
        else:
            tn += 1

    total = tp + fp + fn + tn
    flagged = tp + fp
    auto_approved = fn + tn

    print(f"Evaluated {total} records against the validation layer's needs_review flag.\n")
    print(f"{'':20}{'Actually wrong':>16}{'Actually correct':>18}")
    print(f"{'Flagged':<20}{tp:>16}{fp:>18}   (TP, FP)")
    print(f"{'Not flagged':<20}{fn:>16}{tn:>18}   (FN, TN)")
    print(f"\nPrecision (of flagged, how many were real errors): {ratio(tp, tp + fp):.3f}")
    print(f"Recall (of real errors, how many got flagged):      {ratio(tp, tp + fn):.3f}")

    print("\n--- What this means operationally ---")
    print(f"Extractions with at least one wrong field (before validation): "
          f"{tp + fn}/{total} ({ratio(tp + fn, total):.1%})")
    print(f"Sent to human review:   {flagged}/{total} ({ratio(flagged, total):.1%})")
    print(f"Auto-approved:          {auto_approved}/{total} ({ratio(auto_approved, total):.1%})")
    print(f"Still wrong inside the auto-approved group: {fn}/{auto_approved} "
          f"({ratio(fn, auto_approved):.1%})")

    print(f"\n--- Critical fields only ({', '.join(CRITICAL_FIELDS)}) ---")
    print(f"Extractions with a wrong critical field: {critical_total}/{total}")
    print(f"Of those, flagged for review: {critical_caught}/{critical_total} "
          f"(recall {ratio(critical_caught, critical_total):.3f})")

    if missed_field_counter:
        print("\n--- Which fields were wrong in the missed errors ---")
        for fname, n in missed_field_counter.most_common():
            tag = "  [critical]" if fname in CRITICAL_FIELDS else ""
            print(f"  {fname:<16}{n:>3}{tag}")

    if misses and args.show_examples:
        shown = misses[:args.show_examples]
        print(f"\n--- {len(shown)} of {len(misses)} missed errors, field by field ---")
        for rid, gold, pred, bad in shown:
            describe_miss(rid, gold, pred, bad)


if __name__ == "__main__":
    main()
