"""
Measures the validation layer as a classifier: does "needs_review" agree
with whether the extraction actually had an error, against real ground
truth? Reuses the real-OCR predictions already generated by
colab_end_to_end_eval.ipynb -- no model re-run needed.

A good validation layer should have HIGH RECALL on actual errors (catch
most of what's wrong) even at some cost to precision (flagging a few
correct extractions is cheap -- a human just confirms them; missing a
real error is the expensive failure mode this layer exists to prevent).

Usage (run from inside the repo, e.g. in Colab):
    python3 analyze_validation_layer.py \\
        --gold dataset_full/test.jsonl \\
        --predictions results/finetuned_real_ocr_predictions.jsonl
"""

import argparse
import json

import eval_harness
import validation


def has_real_error(gold_labels, pred):
    """True if the prediction actually diverges from gold on any field --
    the ground-truth answer to 'did this extraction need fixing'."""
    counts = eval_harness.score_record(gold_labels, pred)
    for field_counts in counts.values():
        if field_counts["fp"] > 0 or field_counts["fn"] > 0:
            return True
    return False


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--gold", required=True)
    p.add_argument("--predictions", required=True,
                    help="JSONL cache from run_eval_resumable: {record_id, raw_pred} per line")
    p.add_argument("--show-examples", type=int, default=3,
                    help="How many missed-error (false negative) examples to print for rule refinement")
    args = p.parse_args()

    gold_by_id = {}
    with open(args.gold, encoding="utf-8") as f:
        for line in f:
            rec = json.loads(line)
            gold_by_id[rec["labels"]["record_id"]] = rec["labels"]

    raw_preds_by_id = {}
    with open(args.predictions, encoding="utf-8") as f:
        for line in f:
            entry = json.loads(line)
            raw_preds_by_id[entry["record_id"]] = entry["raw_pred"]

    seen_keys = set()
    tp = fp = fn = tn = 0
    false_negative_examples = []

    for rid, gold in gold_by_id.items():
        raw = raw_preds_by_id.get(rid)
        if raw is None:
            continue  # no cached prediction for this record yet
        pred = eval_harness.extract_json(raw) if isinstance(raw, str) else None

        result = validation.validate_extraction(pred, seen_keys=seen_keys)
        actually_wrong = has_real_error(gold, pred)

        if result.needs_review and actually_wrong:
            tp += 1
        elif result.needs_review and not actually_wrong:
            fp += 1
        elif not result.needs_review and actually_wrong:
            fn += 1
            false_negative_examples.append((rid, gold, pred))
        else:
            tn += 1

    total = tp + fp + fn + tn
    precision = tp / (tp + fp) if (tp + fp) > 0 else float("nan")
    recall = tp / (tp + fn) if (tp + fn) > 0 else float("nan")

    print(f"Evaluated {total} records against the validation layer's needs_review flag.\n")
    print(f"{'':20}{'Actually wrong':>16}{'Actually correct':>18}")
    print(f"{'Flagged':<20}{tp:>16}{fp:>18}   (TP, FP)")
    print(f"{'Not flagged':<20}{fn:>16}{tn:>18}   (FN, TN)")
    print(f"\nPrecision (of flagged, how many were real errors): {precision:.3f}")
    print(f"Recall (of real errors, how many got flagged):      {recall:.3f}")
    print(f"\n{fn} real errors were NOT caught by the validation layer "
          f"({100*fn/(tp+fn):.1f}% of all real errors, if any).")

    if false_negative_examples and args.show_examples:
        print(f"\n--- {min(args.show_examples, len(false_negative_examples))} missed-error examples "
              f"(for refining the rules) ---")
        for rid, gold, pred in false_negative_examples[:args.show_examples]:
            print(f"\nrecord: {rid}")
            print(f"  gold grand_total: {gold.get('grand_total')}  |  pred: {pred.get('grand_total') if pred else None}")
            print(f"  gold invoice_number: {gold.get('invoice_number')}  |  pred: {pred.get('invoice_number') if pred else None}")
            print(f"  gold vendor_tax_id: {gold.get('vendor_tax_id')}  |  pred: {pred.get('vendor_tax_id') if pred else None}")


if __name__ == "__main__":
    main()
